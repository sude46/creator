package com.creator.common.web;

import com.creator.common.ErrorCode;
import org.springframework.http.HttpStatus;

public final class ErrorHttpMapping {
    private ErrorHttpMapping() {
    }

    public static HttpStatus status(ErrorCode code) {
        return switch (code) {
            case INVALID_USERNAME, WEAK_PASSWORD, INVALID_REQUEST, INVALID_PAGE, INVALID_CATEGORY, INVALID_VIDEO, INVALID_TAG, INVALID_REQUEST_KEY, VALIDATION_FAILED, INVALID_MEDIA, INVALID_REVIEW_REASON, INVALID_MODERATION_REASON -> HttpStatus.BAD_REQUEST;
            case USERNAME_TAKEN, ADMIN_BOOTSTRAP_CONFLICT, CATEGORY_NAME_TAKEN, CATEGORY_IN_USE, STALE_WRITE, REQUEST_KEY_CONFLICT, CATEGORY_UNAVAILABLE, UPLOAD_QUOTA_EXCEEDED, SOURCE_ALREADY_BOUND, PROCESSING_RETRY_NOT_ALLOWED, REVIEW_STATE_CONFLICT, PUBLICATION_STATE_CONFLICT -> HttpStatus.CONFLICT;
            case UNAUTHENTICATED, SESSION_INVALID, LOGIN_FAILED -> HttpStatus.UNAUTHORIZED;
            case FORBIDDEN, CSRF_INVALID -> HttpStatus.FORBIDDEN;
            case AUTH_RATE_LIMITED, AUTH_BUSY, UPLOAD_BUSY -> HttpStatus.TOO_MANY_REQUESTS;
            case UPLOAD_TOO_LARGE, REQUEST_TOO_LARGE -> HttpStatus.PAYLOAD_TOO_LARGE;
            case UPLOAD_TIMEOUT -> HttpStatus.REQUEST_TIMEOUT;
            case NOT_FOUND -> HttpStatus.NOT_FOUND;
            case METHOD_NOT_ALLOWED -> HttpStatus.METHOD_NOT_ALLOWED;
            case UNSUPPORTED_MEDIA_TYPE -> HttpStatus.UNSUPPORTED_MEDIA_TYPE;
            case NOT_ACCEPTABLE -> HttpStatus.NOT_ACCEPTABLE;
            case SERVICE_UNAVAILABLE -> HttpStatus.SERVICE_UNAVAILABLE;
            case INTERNAL_ERROR -> HttpStatus.INTERNAL_SERVER_ERROR;
        };
    }
}
